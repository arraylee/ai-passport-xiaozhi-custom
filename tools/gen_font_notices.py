#!/usr/bin/env python3
"""Embed the exact shipped font notices in Flash and preserve source provenance."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "assets/fonts"
LVGL = ROOT / "managed_components/lvgl__lvgl/scripts/built_in_font"
LICENSE_FILES = ("LXGW-v1.522-OFL.txt", "LXGW-OFL.txt", "Montserrat-OFL.txt", "FontAwesome5-LICENSE.txt")
PREAMBLE = """AI PASSPORT - Font notices

The OFL notices below apply to the font software and derived glyph data only.
They do not change the license of the rest of this firmware.
Original font names identify sources and authors, not endorsement.

Passport UI, Passport Body Fallback and Passport Nickname are native 4bpp bitmap derivatives of
LXGW WenKai Medium v1.522 (2026-03-17). The original source font is unchanged.
Source: https://github.com/lxgw/LxgwWenKai/releases/tag/v1.522
Copyright 2021-2026 LXGW (https://github.com/lxgw/LxgwWenKai)
Copyright 2020 The Klee Project Authors (https://github.com/fontworks-fonts/Klee)
The first WenKai notice below is tied to v1.522. The second is the separately
preserved upstream main notice with Reserved Font Names and additional permission.
The product font names do not rely on a Reserved Font Name exception.

Passport Symbols and Latin: LVGL's converted Montserrat and Font Awesome 5 glyphs.
Montserrat Medium v7.200 source: https://github.com/JulietaUla/Montserrat
Copyright 2011 The Montserrat Project Authors (https://github.com/JulietaUla/Montserrat)
Font Awesome 5.9.0 source: https://github.com/FortAwesome/Font-Awesome/tree/5.9.0
WOFF original copyright: Copyright (c) Font Awesome
The accompanying FontAwesome5 notice below is preserved from LVGL v9.5.0,
including its 2022 Fonticons copyright. It does not change the WOFF version.
Source of the converted Latin/symbol fonts and accompanying notices:
https://github.com/lvgl/lvgl/tree/v9.5.0/scripts/built_in_font

Full upstream notices follow, without abridgement.
"""


def render():
    result = PREAMBLE.encode("utf-8")
    licenses = []
    for name in LICENSE_FILES:
        raw = (FONTS / name).read_bytes()
        if b"SIL OPEN FONT LICENSE" not in raw:
            raise ValueError(f"{name}: full OFL notice missing")
        result += f"\n===== {name} =====\n".encode() + raw + b"\n"
        licenses.append({"file": name, "bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest()})
    inputs = [
        (FONTS / "LXGWWenKai-Medium.ttf", "LXGW WenKai Medium", "1.522", "Passport UI / Passport Body Fallback / Passport Nickname"),
        (LVGL / "Montserrat-Medium.ttf", "Montserrat Medium", "7.200", "Passport Symbols and Latin"),
        (LVGL / "FontAwesome5-Solid+Brands+Regular.woff", "Font Awesome 5 Free Solid", "5.9.0", "Passport Symbols and Latin"),
    ]
    sources = [{"file": str(p.relative_to(ROOT)), "source_family": family, "version": version,
                "derived_family": derived, "bytes": p.stat().st_size,
                "sha256": hashlib.sha256(p.read_bytes()).hexdigest()}
               for p, family, version, derived in inputs]
    manifest = {"schema": 1, "scope": "font software and derived glyph data only",
                "sources": sources, "licenses": licenses,
                "embedded_notice": {"file": "FONT-LICENSES.txt", "bytes": len(result),
                                    "sha256": hashlib.sha256(result).hexdigest()}}
    # JSON string escaping preserves Unicode and CRLF bytes in the C string.
    literals = "\n".join(json.dumps(line, ensure_ascii=False) for line in result.decode("utf-8").splitlines(keepends=True))
    code = ('/* Generated by tools/gen_font_notices.py; do not edit notices here. */\n'
            '#include "presentation/font_notices.h"\n\n'
            'const char passport_font_notices[] =\n' + literals + ';\n')
    return {
        FONTS / "FONT-LICENSES.txt": result,
        FONTS / "font-sources.json": (json.dumps(manifest, indent=2, ensure_ascii=False) + "\n").encode(),
        ROOT / "components/ui/presentation/src/font_notices.c": code.encode(),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, data in render().items():
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                raise SystemExit(f"Stale font notice output: {path.relative_to(ROOT)}")
        else:
            path.write_bytes(data)
        print(f"{path.relative_to(ROOT)}: {len(data)} bytes")


if __name__ == "__main__":
    main()
