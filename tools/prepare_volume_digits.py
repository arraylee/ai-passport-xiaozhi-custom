"""Subset the bundled Montserrat bitmap to 0–9 without rasterizing it again.

The source font is licensed under SIL OFL 1.1; see assets/fonts/Montserrat-OFL.txt.
The derived font is named Passport Volume Digits. No font converter is required.
"""
from pathlib import Path
import argparse
import re


def generate(root):
    source = root / "managed_components/lvgl__lvgl/src/font/lv_font_montserrat_48.c"
    text = re.sub(r"/\*.*?\*/", "", source.read_text(), flags=re.S)
    bitmap_section = re.search(r"glyph_bitmap\[\]\s*=\s*\{(.*?)\};", text, re.S)[1]
    bitmap = bytes(int(n, 16) for n in re.findall(r"0x[0-9a-fA-F]+", bitmap_section))
    descriptors = re.search(r"glyph_dsc\[\]\s*=\s*\{(.*?)\};", text, re.S)[1]
    glyphs = [dict((k, int(v)) for k, v in re.findall(r"\.(\w+)\s*=\s*(-?\d+)", item))
              for item in re.findall(r"\{([^}]+)\}", descriptors)]
    assert re.search(r"\.range_start = 32, .range_length = 95, .glyph_id_start = 1", text)
    first = ord("0") - 32 + 1
    start, end = glyphs[first]["bitmap_index"], glyphs[first + 10]["bitmap_index"]
    digits = bitmap[start:end]
    lines = ["/* Generated by tools/prepare_volume_digits.py. Do not edit.",
             " * Passport Volume Digits: subset of Montserrat, SIL OFL 1.1.",
             " * License and copyright: assets/fonts/Montserrat-OFL.txt */",
             "static const uint8_t xz_digits_bitmap[] = {"]
    lines += ["    " + ", ".join(f"0x{v:02x}" for v in digits[i:i+16]) + ","
              for i in range(0, len(digits), 16)]
    lines += ["};", "static const lv_font_fmt_txt_glyph_dsc_t xz_digits_glyphs[] = {", "    {0},"]
    for g in glyphs[first:first+10]:
        g["bitmap_index"] -= start
        lines.append("    {" + ", ".join(f".{k} = {v}" for k, v in g.items()) + "},")
    lines += ["};", "static const lv_font_fmt_txt_cmap_t xz_digits_cmaps[] = {{",
              "    .range_start = 48, .range_length = 10, .glyph_id_start = 1,",
              "    .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY,", "}};",
              "static const lv_font_fmt_txt_dsc_t xz_digits_dsc = {",
              "    .glyph_bitmap = xz_digits_bitmap, .glyph_dsc = xz_digits_glyphs,",
              "    .cmaps = xz_digits_cmaps, .cmap_num = 1, .bpp = 4, .bitmap_format = 0,", "};",
              "static const lv_font_t xz_volume_digits = {",
              "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,",
              "    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,",
              "    .line_height = 52, .base_line = 9, .subpx = LV_FONT_SUBPX_NONE,",
              "    .underline_position = -4, .underline_thickness = 2, .dsc = &xz_digits_dsc,", "};", ""]
    return "\n".join(lines), len(digits)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    output, bitmap_bytes = generate(root)
    target = root / "components/ui/presentation/src/xiaozhi_volume_digits.inc"
    if args.check:
        assert target.read_text() == output, "Volume digits are stale"
    else:
        target.write_text(output)
    print(f"Passport Volume Digits: 10 glyphs, {bitmap_bytes} bitmap bytes; exact bundled glyph pixels")


if __name__ == "__main__":
    main()
